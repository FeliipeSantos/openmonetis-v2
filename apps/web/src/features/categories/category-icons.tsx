export const categoryIconOptions = categoryIconGroups.flatMap((group) => group.options);

const categoryIconsByValue = new Map(categoryIconOptions.map((item) => [item.value, item.icon]));

export function CategoryIcon({ className, name }: { className?: string; name?: string | null }) {
  const Icon = (name ? categoryIconsByValue.get(name) : undefined) ?? Tag;
  return <Icon aria-hidden="true" className={cn("size-5", className)} />;
}
